// Renders the React <Icon> components to static SVG strings and minifies the
// shared stylesheet into functions/_lib/generated.js, so the share pages served
// by Cloudflare Functions reuse the homepage's components and styles without
// shipping React to the Worker. Runs automatically before `npm run build`.
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUTPUT = join(root, "functions", "_lib", "generated.js");

export function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,>])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

async function renderIcons() {
  const result = await build({
    stdin: {
      contents: `
        import { createElement } from "react";
        import { renderToStaticMarkup } from "react-dom/server";
        import { Icon, ICON_NAMES } from "./src/components/icons/Icon.tsx";
        export const icons = Object.fromEntries(ICON_NAMES.map((name) => [name, renderToStaticMarkup(createElement(Icon, { name }))]));
      `,
      resolveDir: root,
      loader: "tsx",
    },
    bundle: true,
    platform: "node",
    format: "esm",
    jsx: "automatic",
    packages: "external",
    write: false,
    logLevel: "silent",
  });
  const cacheDir = join(root, "node_modules", ".cache");
  mkdirSync(cacheDir, { recursive: true });
  const entry = join(cacheDir, `mdshare-icons-${process.pid}.mjs`);
  writeFileSync(entry, result.outputFiles[0].text);
  const { icons } = await import(pathToFileURL(entry).href);
  return icons;
}

export async function generate() {
  const icons = await renderIcons();
  const css = minifyCss(readFileSync(join(root, "src", "styles", "shared.css"), "utf8"));
  return [
    "// AUTO-GENERATED by scripts/generate-shared.mjs from src/components/icons/Icon.tsx",
    "// and src/styles/shared.css. Do not edit by hand; run `npm run generate`.",
    `export const ICONS = ${JSON.stringify(icons, null, 2)};`,
    `export const SHARED_CSS = ${JSON.stringify(css)};`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, await generate());
  console.log(`generated ${OUTPUT}`);
}
